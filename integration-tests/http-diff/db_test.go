// setupDatabase creates a database migrated by the Go implementation and
// loads seed.sql (the data of the reference database) into it. The schema
// is identical to the one Node creates, so the result equals record.sh's
// databases.
func setupDatabase(t *testing.T, name string) string {
	t.Helper()
	// MEDUSA_TEST_DB_PREFIX lets parallel runs (other checkouts) use their own databases.
	name = os.Getenv("MEDUSA_TEST_DB_PREFIX") + name
	admin := os.Getenv("MEDUSA_TEST_PG_ADMIN_URL")
	if admin == "" {
		t.Skip("MEDUSA_TEST_PG_ADMIN_URL is not set (e.g. postgres://postgres:postgres@localhost:54329/postgres)")
	}
	ctx := context.Background()
	conn, err := pgx.Connect(ctx, admin)
	if err != nil {
		t.Fatal(err)
	}
	for _, sql := range []string{"drop database if exists " + name + " with (force)", "create database " + name} {
		if _, err := conn.Exec(ctx, sql); err != nil {
			t.Fatal(err)
		}
	}
	conn.Close(ctx)

	u, _ := url.Parse(admin)
	u.Path = "/" + name
	dbURL := u.String()
	cfg := config.DefineConfig(config.InputConfig{ProjectConfig: config.ProjectConfig{DatabaseURL: dbURL}, Modules: scenarioModules(), Plugins: scenarioPlugins()})
	if err := db.Migrate(ctx, cfg, db.MigrateOptions{}); err != nil {
		t.Fatal(err)
	}
	c, err := pgx.Connect(ctx, dbURL)
	if err != nil {
		t.Fatal(err)
	}
	defer c.Close(ctx)
	if _, err := c.Exec(ctx, `
    DO $$ DECLARE t text; BEGIN
      FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public'
        AND tablename NOT IN ('mikro_orm_migrations', 'script_migrations', 'link_module_migrations')
      LOOP EXECUTE format('TRUNCATE %I CASCADE', t); END LOOP;
    END $$;`); err != nil {
		t.Fatal(err)
	}
	if _, err := c.Exec(ctx, seedSQL(t), pgx.QueryExecModeSimpleProtocol); err != nil {
		t.Fatal(fmt.Errorf("loading seed.sql: %w", err))
	}
	// SEED_MIGRATE_SEARCH=true: the search indexes are migrated again on
	// the seeded data (record.sh runs `medusa db:migrate:search`).
	if os.Getenv("SEED_MIGRATE_SEARCH") == "true" {
		if err := db.MigrateSearch(ctx, cfg, db.MigrateSearchOptions{}); err != nil {
			t.Fatal(err)
		}
	}
	return dbURL
}

var seedText string

func seedSQL(t *testing.T) string {
	if seedText == "" {
		raw, err := os.ReadFile("seed.sql")
		if err != nil {
			t.Fatal(err)
		}
		seedText = string(raw)
	}
	return seedText
}

var (
	idRe   = regexp.MustCompile(`^(?:[a-z_]+_)?[0-9A-HJKMNP-TV-Z]{26}$`)
	dateRe = regexp.MustCompile(`^(\d{4}-\d\d-\d\d)T(\d\d:\d\d:\d\d)(?:\.(\d{3}))?Z$`)
)

// API key tokens (random) and their redacted form.
var (
	apiTokenRe      = regexp.MustCompile(`^(pk|sk)_[0-9a-f]{64}$`)
	redactedTokenRe = regexp.MustCompile(`^(pk|sk)_[0-9a-f]{3}\*\*\*[0-9a-f]{3}$`)
	// crypto.randomUUID() (order transfer tokens)
	// workflow transaction ids generated by run()
	transactionIDRe = regexp.MustCompile(`^auto-[0-9A-HJKMNP-TV-Z]{26}$`)
	uuidRe          = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$`)
	// loyalty plugin codes (generateCode: prefix and random sections of 4
	// characters, similar-looking ones excluded), e.g. SC-ABCD-EFGH-JKLM-NPQR
	loyaltyCodeRe = regexp.MustCompile(`^[A-Z]+(-[ABCDEFGHJKLMNPQRSTUVWXYZ2-9]{4}){3,}$`)
)

// isGenerated reports whether a string is an id or a timestamp produced
// during the scenario (absent from seed.sql).
func isGenerated(s string) (bool, string) {
	if idRe.MatchString(s) {
		return !strings.Contains(seedText, "'"+s+"'"), "id"
	}
	if apiTokenRe.MatchString(s) {
		return !strings.Contains(seedText, "'"+s+"'"), "token"
	}
	if transactionIDRe.MatchString(s) {
		return true, "transaction"
	}
	if uuidRe.MatchString(s) {
		return !strings.Contains(seedText, "'"+s+"'"), "uuid"
	}
	if loyaltyCodeRe.MatchString(s) {
		return !strings.Contains(seedText, "'"+s+"'"), "code"
	}
	if redactedTokenRe.MatchString(s) {
		return !strings.Contains(seedText, "'"+s+"'"), "redacted"
	}
	if m := dateRe.FindStringSubmatch(s); m != nil {
		ms := strings.TrimRight(m[3], "0")
		pg := m[1] + " " + m[2]
		if ms != "" {
			pg += "." + ms
		}
		return !strings.Contains(seedText, "'"+pg+"+00'"), "date"
	}
	return false, ""
}

// scenarioModules are the modules a scenario's environment adds to the
// default configuration, like the reference application's
// medusa-config.js: the index engine needs the index module besides its
// feature flag (MEDUSA_FF_INDEX_ENGINE=true).
//
// MEDUSA_TEST_LOCKING_PROVIDER (postgres or redis) makes the provider the
// default of the locking module, MEDUSA_TEST_CACHE=redis selects
// cache-redis; both use MEDUSA_TEST_REDIS_URL.
// The brand test module (testapp) is added with MEDUSA_TEST_BRAND=true.
// indexModuleOptions mirrors the index module options of the reference app
// (testapp/medusa-config.js): MEDUSA_TEST_INDEX_SCHEMA names a GraphQL file
// of testapp/index-schemas used as the `schema` option,
// MEDUSA_TEST_INDEX_SCHEMA_RESTART replaces it.
func indexModuleOptions() map[string]any {
	name := os.Getenv("MEDUSA_TEST_INDEX_SCHEMA_RESTART")
	if name == "" {
		name = os.Getenv("MEDUSA_TEST_INDEX_SCHEMA")
	}
	if name == "" {
		return nil
	}
	data, err := os.ReadFile(filepath.Join("testapp", "index-schemas", name))
	if err != nil {
		panic(err)
	}
	return map[string]any{"schema": string(data)}
}

// scenarioPlugins are the plugins of a scenario: HTTP_DIFF_LOYALTY=true
// enables @medusajs/loyalty-plugin (the reference application reads the
// same variable).
func scenarioPlugins() []config.PluginConfig {
	if os.Getenv("HTTP_DIFF_LOYALTY") == "true" {
		return []config.PluginConfig{{Resolve: loyaltyplugin.Name, Options: map[string]any{}}}
	}
	return nil
}

func scenarioModules() []config.ModuleConfig {
	var out []config.ModuleConfig
	if os.Getenv("MEDUSA_FF_INDEX_ENGINE") == "true" {
		out = append(out, config.ModuleConfig{Key: "index", Resolve: "@medusajs/medusa/index-module", Options: indexModuleOptions()})
	}
	switch os.Getenv("MEDUSA_TEST_LOCKING_PROVIDER") {
	case "postgres":
		out = append(out, config.ModuleConfig{Key: "locking", Resolve: "@medusajs/medusa/locking", Providers: []config.ModuleProviderConfig{
			{Resolve: "@medusajs/medusa/locking-postgres", ID: "locking-postgres", IsDefault: true},
		}})
	case "redis":
		out = append(out, config.ModuleConfig{Key: "locking", Resolve: "@medusajs/medusa/locking", Providers: []config.ModuleProviderConfig{
			{Resolve: "@medusajs/medusa/locking-redis", ID: "locking-redis", IsDefault: true, Options: map[string]any{"redisUrl": os.Getenv("MEDUSA_TEST_REDIS_URL")}},
		}})
	}
	if os.Getenv("MEDUSA_TEST_CACHE") == "redis" {
		out = append(out, config.ModuleConfig{Key: "cache", Resolve: "@medusajs/medusa/cache-redis", Options: map[string]any{"redisUrl": os.Getenv("MEDUSA_TEST_REDIS_URL")}})
	}
	if m, ok := paymentModule(); ok {
		out = append(out, m)
	}
	if m, ok := fulfillmentModule(); ok {
		out = append(out, m)
	}
	if os.Getenv("MEDUSA_TEST_BRAND") == "true" {
		out = append(out, config.ModuleConfig{Resolve: "./src/modules/brand", Module: &brand.Module.ModuleExports})
	}
	out = append(out, envModules()...)
	return append(out, redisScenarioModules()...)
}
