#!/usr/bin/env node
//
// Generates packages/core/utils/src/defaults (default currencies and
// countries) from the upstream @medusajs/utils defaults, keeping their order.
//
// Usage:
//   node scripts/extract-defaults.mjs [UPSTREAM_DIR]

import { execFileSync } from "node:child_process"
import { createRequire } from "node:module"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const UPSTREAM = path.resolve(process.argv[2] ?? path.join(ROOT, "reference/medusa"))
const VERSION = fs.readFileSync(path.join(ROOT, "UPSTREAM_VERSION"), "utf8").trim()
const HEADER = `// Code generated by scripts/extract-defaults.mjs from Medusa ${VERSION}. DO NOT EDIT.`
const require = createRequire(path.join(UPSTREAM, "package.json"))
const utils = require("@medusajs/framework/utils")

const out = path.join(ROOT, "packages/core/utils/src/defaults")
fs.mkdirSync(out, { recursive: true })
const q = (v) => JSON.stringify(v)

const currencies = Object.values(utils.defaultCurrencies)
fs.writeFileSync(
  path.join(out, "currencies.go"),
  `${HEADER}

// Package defaults mirrors @medusajs/utils/src/defaults.
package defaults

// Currency mirrors an entry of defaultCurrencies.
type Currency struct {
	Symbol        string
	Name          string
	SymbolNative  string
	DecimalDigits int
	Rounding      float64
	Code          string
	NamePlural    string
}

// DefaultCurrencies mirrors defaultCurrencies, in upstream order.
var DefaultCurrencies = []Currency{
${currencies.map((c) => `\t{Symbol: ${q(c.symbol)}, Name: ${q(c.name)}, SymbolNative: ${q(c.symbol_native)}, DecimalDigits: ${c.decimal_digits}, Rounding: ${c.rounding}, Code: ${q(c.code)}, NamePlural: ${q(c.name_plural)}},`).join("\n")}
}
`
)

const countries = utils.DefaultsUtils.defaultCountries
fs.writeFileSync(
  path.join(out, "countries.go"),
  `${HEADER}

package defaults

// Country mirrors an entry of defaultCountries.
type Country struct {
	Alpha2  string
	Name    string
	Alpha3  string
	Numeric string
}

// DefaultCountries mirrors defaultCountries, in upstream order.
var DefaultCountries = []Country{
${countries.map((c) => `\t{Alpha2: ${q(c.alpha2)}, Name: ${q(c.name)}, Alpha3: ${q(c.alpha3)}, Numeric: ${q(c.numeric)}},`).join("\n")}
}
`
)
execFileSync("gofmt", ["-w", out])
console.log(`currencies: ${currencies.length}, countries: ${countries.length}`)
