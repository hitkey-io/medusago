#!/usr/bin/env node
//
// Generates the Go link definitions from the compiled Medusa link-modules
// package.
//
// Usage:
//   node scripts/extract-links.mjs [UPSTREAM_DIR]
//
// Every definition exported by link-modules/src/definitions/index.ts (and
// readonly/index.ts) is serialized to JSON and written to
// packages/modules/link-modules/src/definitions/[readonly/]<file>.go, where it
// is decoded into joiner.ModuleJoinerConfig with unknown keys rejected.
// Medusa Enterprise Edition files are skipped.
//
// It also writes testdata/upstream-link-sql.json next to the Go entity
// generator: the create SQL upstream produces for every link table, used to
// verify the Go port.

import { execFileSync } from "node:child_process"
import { createRequire } from "node:module"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const UPSTREAM = path.resolve(process.argv[2] ?? path.join(ROOT, "reference/medusa"))
const VERSION = fs.readFileSync(path.join(ROOT, "UPSTREAM_VERSION"), "utf8").trim()
const GO_MODULE = "github.com/hitkey-io/medusago"
const HEADER = `// Code generated by scripts/extract-links.mjs from Medusa ${VERSION}. DO NOT EDIT.`

const require = createRequire(path.join(UPSTREAM, "package.json"))
const PKG = "packages/modules/link-modules"
const distDefs = path.join(UPSTREAM, PKG, "dist/definitions")
const outDefs = path.join(ROOT, PKG, "src/definitions")

const enterprisePaths = fs
  .readFileSync(path.join(UPSTREAM, "ENTERPRISE-LICENSE.md"), "utf8")
  .split("\n")
  .map((l) => l.match(/^- `(.*)`$/)?.[1])
  .filter(Boolean)

const isEnterprise = (rel) =>
  enterprisePaths.some((p) => `${PKG}/src/definitions/${rel}.ts` === p || `${PKG}/src/definitions/${rel}`.startsWith(p.replace(/\/$/, "") + "/"))

const goIdent = (name) => name.replace(/[^A-Za-z0-9_]/g, "")

function generate(subdir, pkgName) {
  const dir = path.join(distDefs, subdir)
  const index = require(path.join(dir, "index.js"))
  const exported = new Map(Object.entries(index).map(([name, value]) => [value, name]))
  const outDir = path.join(outDefs, subdir)
  fs.mkdirSync(outDir, { recursive: true })
  for (const f of fs.readdirSync(outDir)) {
    if (f.endsWith(".go") && fs.readFileSync(path.join(outDir, f), "utf8").startsWith(HEADER)) {
      fs.rmSync(path.join(outDir, f))
    }
  }

  const written = new Map()
  for (const file of fs.readdirSync(dir).sort()) {
    if (!file.endsWith(".js") || file === "index.js") {
      continue
    }
    const base = file.replace(/\.js$/, "")
    const rel = path.join(subdir, base)
    if (isEnterprise(rel)) {
      continue
    }
    const mod = require(path.join(dir, file))
    const vars = []
    for (const [name, value] of Object.entries(mod)) {
      if (!exported.has(value)) {
        continue
      }
      const json = JSON.stringify(value, null, 2)
      if (json.includes("`")) {
        throw new Error(`${rel}: backtick in definition`)
      }
      vars.push(`// ${name} mirrors ${name} from ${rel}.ts.\nvar ${goIdent(name)} = joiner.MustParseModuleJoinerConfig(\`${json}\`)`)
      written.set(value, goIdent(name))
    }
    if (!vars.length) {
      continue
    }
    fs.writeFileSync(
      path.join(outDir, `${base}.go`),
      `${HEADER}

package ${pkgName}

import "${GO_MODULE}/packages/core/types/src/joiner"

${vars.join("\n\n")}
`
    )
  }

  // index.go keeps the upstream export order.
  const ordered = Object.values(index)
    .filter((v) => written.has(v))
    .map((v) => written.get(v))
  fs.writeFileSync(
    path.join(outDir, "index.go"),
    `${HEADER}

${subdir ? "" : "// Package definitions mirrors @medusajs/link-modules/src/definitions.\n"}package ${pkgName}

import "${GO_MODULE}/packages/core/types/src/joiner"

// All lists the definitions in upstream export order.
var All = []*joiner.ModuleJoinerConfig{
${ordered.map((n) => `\t${n},`).join("\n")}
}
`
  )
  return { definitions: written }
}

const core = generate("", "definitions")
const readonly = generate("readonly", "readonly")

// Exported definitions skipped as Enterprise materials (the core index also
// re-exports the read-only definitions, which are generated separately).
const coreIndex = require(path.join(distDefs, "index.js"))
const readonlyValues = new Set(readonly.definitions.keys())
const skippedEnterprise = Object.values(coreIndex).filter(
  (v) => !core.definitions.has(v) && !readonlyValues.has(v)
).length

// Upstream create SQL per link table, for the Go entity generator tests.
const { MikroORM } = require("@medusajs/framework/mikro-orm/core")
const { PostgreSqlDriver } = require("@medusajs/framework/mikro-orm/postgresql")
const { normalizeMigrationSQL } = require("@medusajs/framework/utils")
const { generateEntity } = require(path.join(UPSTREAM, PKG, "dist/utils/index.js"))

const expected = {}
for (const [cfg] of core.definitions) {
  if (cfg.isReadOnlyLink || !cfg.relationships) {
    continue
  }
  const [primary, foreign] = cfg.relationships
  const entity = generateEntity(cfg, primary, foreign)
  const orm = await MikroORM.init({
    driver: PostgreSqlDriver,
    entities: [entity],
    dbName: "unused",
    connect: false,
    discovery: { warnWhenNoEntities: false },
  })
  expected[entity.meta.collection] = normalizeMigrationSQL(await orm.getSchemaGenerator().getCreateSchemaSQL())
  await orm.close(true)
}
const testdata = path.join(ROOT, PKG, "src/utils/testdata")
fs.mkdirSync(testdata, { recursive: true })
fs.writeFileSync(path.join(testdata, "upstream-link-sql.json"), JSON.stringify(expected, null, 2) + "\n")

execFileSync("gofmt", ["-w", outDefs])

console.log(`definitions: ${core.definitions.size} (+${readonly.definitions.size} read-only), skipped enterprise: ${skippedEnterprise}`)
console.log(`link tables with upstream SQL: ${Object.keys(expected).length}`)
