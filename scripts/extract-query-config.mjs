#!/usr/bin/env node
//
// Generates packages/core/modules-sdk/src/default-query-config.go from the
// JSON written by scripts/extract-query-config.js (run with `medusa exec` in
// the reference application): the joiner configs Query is built from and the
// relation map extracted from the merged GraphQL schema, for the default
// modules. databaseClientUrl is dropped.
//
// Usage:
//   node scripts/extract-query-config.mjs <query-config.json>
//   node scripts/extract-query-config.mjs <flag.json> --variant <name> --base <default.json>
//
// The variant form writes default-query-config-<name>.go: what a feature flag
// adds to the default configuration (e.g. the translation module and its
// read-only links), as the joiner configs and relations missing from the
// base dump. Both dumps must come from the same database.

import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const VERSION = fs.readFileSync(path.join(ROOT, "UPSTREAM_VERSION"), "utf8").trim()
const HEADER = `// Code generated by scripts/extract-query-config.mjs from Medusa ${VERSION}. DO NOT EDIT.`

const input = JSON.parse(fs.readFileSync(process.argv[2], "utf8"))
const argValue = (name) => {
  const i = process.argv.indexOf(name)
  return i === -1 ? undefined : process.argv[i + 1]
}
const variant = argValue("--variant")
if (variant) {
  writeVariant(variant, JSON.parse(fs.readFileSync(argValue("--base"), "utf8")))
  process.exit(0)
}
const configs = input.joinerConfigs.map(({ databaseClientUrl, ...rest }) => rest)
const json = JSON.stringify(configs, null, 2)
if (json.includes("`")) {
  throw new Error("backtick in joiner configs")
}
const relations = Object.keys(input.relationMap)
  .sort()
  .map((entity) => {
    const props = Object.entries(input.relationMap[entity])
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([prop, target]) => `${JSON.stringify(prop)}: ${JSON.stringify(target)}`)
      .join(", ")
    return `\t${JSON.stringify(entity)}: {${props}},`
  })
  .join("\n")

const out = path.join(ROOT, "packages/core/modules-sdk/src/default-query-config.go")
fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(
  out,
  `${HEADER}

// Package modulessdk mirrors @medusajs/modules-sdk: the module runtime.
package modulessdk

import "github.com/hitkey-io/medusago/packages/core/types/src/joiner"

// DefaultJoinerConfigs are the joiner configs of the queryable modules and
// link modules loaded with the default configuration, as given to Query.
var DefaultJoinerConfigs = joiner.MustParseModuleJoinerConfigs(\`${json}\`)

// DefaultRelationMap maps entity -> property -> related entity, extracted
// from the merged GraphQL schema of the default modules.
var DefaultRelationMap = map[string]map[string]string{
${relations}
}
`
)
execFileSync("gofmt", ["-w", out])
console.log(`joiner configs: ${configs.length}, relation map entities: ${Object.keys(input.relationMap).length}`)

function writeVariant(name, base) {
  const strip = ({ databaseClientUrl, ...rest }) => rest
  const known = new Set(base.joinerConfigs.map((c) => JSON.stringify(strip(c))))
  const added = input.joinerConfigs.map(strip).filter((c) => !known.has(JSON.stringify(c)))
  if (input.joinerConfigs.length - added.length !== base.joinerConfigs.length) {
    throw new Error("the base joiner configs are not all part of the variant")
  }
  const relations = []
  for (const entity of Object.keys(input.relationMap).sort()) {
    const baseProps = base.relationMap[entity] ?? {}
    for (const [prop, target] of Object.entries(input.relationMap[entity]).sort(([a], [b]) => a.localeCompare(b))) {
      if (prop in baseProps) {
        if (baseProps[prop] !== target) {
          throw new Error(`relation ${entity}.${prop} changed`)
        }
        continue
      }
      relations.push([entity, prop, target])
    }
    if (!(entity in base.relationMap) && !Object.keys(input.relationMap[entity]).length) {
      relations.push([entity])
    }
  }
  const json = JSON.stringify(added, null, 2)
  if (json.includes("`")) {
    throw new Error("backtick in joiner configs")
  }
  const ident = name.replace(/(^|[-_])([a-z])/g, (_, __, c) => c.toUpperCase())
  const byEntity = new Map()
  for (const [entity, prop, target] of relations) {
    const props = byEntity.get(entity) ?? []
    if (prop) {
      props.push(`${JSON.stringify(prop)}: ${JSON.stringify(target)}`)
    }
    byEntity.set(entity, props)
  }
  const relationLines = [...byEntity.entries()]
    .map(([entity, props]) => `\t${JSON.stringify(entity)}: {${props.join(", ")}},`)
    .join("\n")
  const out = path.join(ROOT, `packages/core/modules-sdk/src/default-query-config-${name}.go`)
  fs.writeFileSync(
    out,
    `${HEADER}

package modulessdk

import "github.com/hitkey-io/medusago/packages/core/types/src/joiner"

// ${ident}JoinerConfigs are the joiner configs the "${name}" feature flag adds
// to DefaultJoinerConfigs (its module and read-only links).
var ${ident}JoinerConfigs = joiner.MustParseModuleJoinerConfigs(\`${json}\`)

// ${ident}RelationMap holds the relations the "${name}" feature flag adds to
// DefaultRelationMap.
var ${ident}RelationMap = map[string]map[string]string{
${relationLines}
}
`
  )
  execFileSync("gofmt", ["-w", out])
  console.log(`${name}: joiner configs: ${added.length}, relations: ${relations.length}`)
}
