#!/usr/bin/env node
//
// Generates packages/modules/providers/payment-adyen/src/client/typemap.go:
// the Checkout API models (attributeTypeMap, discriminator, mapping) that the
// Adyen Node library's ObjectSerializer uses to serialize the requests and
// deserialize the responses of the endpoints @medusajs/payment-adyen calls.
// The serializer orders and filters object keys by these maps, so the Go
// client applies the same ones.
//
// Usage:
//   node scripts/extract-adyen-types.mjs [UPSTREAM_DIR]

import { execFileSync } from "node:child_process"
import { createRequire } from "node:module"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const UPSTREAM = path.resolve(process.argv[2] ?? path.join(ROOT, "reference/medusa"))
const VERSION = fs.readFileSync(path.join(ROOT, "UPSTREAM_VERSION"), "utf8").trim()
const require = createRequire(
  createRequire(path.join(UPSTREAM, "package.json")).resolve("@medusajs/payment-adyen")
)
const libPkg = require("@adyen/api-library/package.json")

// The serializer's typeMap is module-private: read its entries
// ("Name": file_1.Export) from objectSerializer.js and load the classes.
const serializerFile = require.resolve("@adyen/api-library/lib/src/typings/checkout/objectSerializer")
const serializerSrc = fs.readFileSync(serializerFile, "utf8")
const files = {}
for (const [, v, f] of serializerSrc.matchAll(/const (\w+)_1 = require\("\.\/(\w+)"\)/g)) files[v] = f
const checkout = {}
const typeMapSrc = serializerSrc.slice(serializerSrc.indexOf("let typeMap = {"))
for (const [, name, v, exp] of typeMapSrc.matchAll(/"(\w+)": (\w+)_1\.(\w+),/g)) {
  checkout[name] = require(path.join(path.dirname(serializerFile), files[v]))[exp]
}

const ROOTS = [
  "PaymentMethodsRequest",
  "PaymentMethodsResponse",
  "PaymentRequest",
  "PaymentResponse",
  "PaymentDetailsRequest",
  "PaymentDetailsResponse",
  "PaymentCaptureRequest",
  "PaymentCaptureResponse",
  "PaymentRefundRequest",
  "PaymentRefundResponse",
  "PaymentCancelRequest",
  "PaymentCancelResponse",
  "PaymentReversalRequest",
  "PaymentReversalResponse",
  "StoredPaymentMethodRequest",
  "StoredPaymentMethodResource",
  "ListStoredPaymentMethodsResponse",
]

const PRIMITIVES = ["string", "boolean", "double", "integer", "long", "float", "number", "any", "date"]

// referenced model names of a type string (Array<X>, X | null, { [key: string]: X; })
function refs(type) {
  return (type.match(/[A-Za-z0-9_.]+/g) ?? []).filter(
    (t) => !PRIMITIVES.includes(t.toLowerCase()) && !t.includes(".") && t !== "key" && t !== "null" && t !== "undefined" && t !== "Array" && t !== "Set"
  )
}

const models = {}
const queue = [...ROOTS]
while (queue.length) {
  const name = queue.shift()
  if (models[name] !== undefined) continue
  const cls = checkout[name]
  if (!cls) {
    models[name] = null
    continue
  }
  if (typeof cls.getAttributeTypeMap !== "function") {
    // oneOf classes: a discriminator and a mapping, no attributes
    models[name] = { discriminator: cls.discriminator ?? null, mapping: cls.mapping ?? null, attrs: null }
    for (const m of Object.values(cls.mapping ?? {})) queue.push(m)
    continue
  }
  const attrs = cls.getAttributeTypeMap()
  models[name] = {
    discriminator: cls.discriminator ?? null,
    mapping: cls.mapping ?? null,
    attrs: attrs.map((a) => [a.name, a.baseName, a.type, a.format ?? ""]),
  }
  for (const a of attrs) queue.push(...refs(a.type))
  for (const m of Object.values(cls.mapping ?? {})) queue.push(m)
}

const q = (v) => JSON.stringify(v)
let out = `// Code generated by scripts/extract-adyen-types.mjs from Medusa ${VERSION} (@adyen/api-library ${libPkg.version}). DO NOT EDIT.

package client

// TypeMap are the Checkout API models of the Adyen library's ObjectSerializer.
var TypeMap = map[string]*Model{
`
for (const name of Object.keys(models).sort()) {
  const m = models[name]
  if (!m) continue
  out += `\t${q(name)}: {\n`
  if (m.discriminator) out += `\t\tDiscriminator: ${q(m.discriminator)},\n`
  if (m.mapping) {
    out += `\t\tMapping: map[string]string{`
    out += Object.entries(m.mapping).map(([k, v]) => `${q(k)}: ${q(v)}`).join(", ")
    out += `},\n`
  }
  if (m.attrs === null) {
    out += `\t\tNoAttributes: true,\n\t},\n`
    continue
  }
  out += `\t\tAttrs: []Attr{\n`
  for (const [n, b, t, f] of m.attrs) out += `\t\t\t{${q(n)}, ${q(b)}, ${q(t)}, ${q(f)}},\n`
  out += `\t\t},\n\t},\n`
}
out += `}\n`

const file = path.join(ROOT, "packages/modules/providers/payment-adyen/src/client/typemap.go")
fs.mkdirSync(path.dirname(file), { recursive: true })
fs.writeFileSync(file, out)
execFileSync("gofmt", ["-w", file])
console.log(`${file}: ${Object.values(models).filter(Boolean).length} models`)
