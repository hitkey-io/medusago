#!/usr/bin/env node
//
// Generates packages/core/workflows-sdk/src/utils/composer/upstream-flows.go
// from the JSON written by scripts/extract-workflow-flows.js (run with
// `medusa exec` in the reference application): the step graph upstream
// composes for every workflow, which the journal of a Go run follows (step
// ids, depth, next, the definitions of the steps that did not run).
//
// Usage:
//   node scripts/extract-workflow-flows.mjs <flows.json>
//
// The uuids are blanked (generated when a workflow is composed); the key
// keeps its place in the definition. Workflows of
// the Medusa Enterprise Edition (RBAC) are skipped.

import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const VERSION = fs.readFileSync(path.join(ROOT, "UPSTREAM_VERSION"), "utf8").trim()
const HEADER = `// Code generated by scripts/extract-workflow-flows.mjs from Medusa ${VERSION}. DO NOT EDIT.`
const OUT = path.join(ROOT, "packages/core/workflows-sdk/src/utils/composer/upstream-flows.go")

const ENTERPRISE = /rbac|^(un)?assign-roles$|^get-assignable-(roles|policies)-workflow$/

const input = JSON.parse(fs.readFileSync(process.argv[2], "utf8"))

const strip = (node) => {
  if (Array.isArray(node)) {
    return node.map(strip)
  }
  if (!node || typeof node !== "object") {
    return node
  }
  const out = {}
  for (const [k, v] of Object.entries(node)) {
    // the uuid keeps its place in the definition (generated per process)
    out[k] = k === "next" ? strip(v) : k === "uuid" ? "" : v
  }
  return out
}

const flows = {}
for (const id of Object.keys(input).sort()) {
  if (ENTERPRISE.test(id)) {
    continue
  }
  flows[id] = { options: input[id].options ?? {}, flow: strip(input[id].flow) }
}

const json = JSON.stringify(flows, null, 1)
if (json.includes("`")) {
  throw new Error("backtick in the workflow flows")
}

const code = `${HEADER}

package composer

// upstreamFlowsJSON holds, keyed by workflow id, the options a workflow is
// created with and the step graph upstream composes for it (the
// WorkflowManager flow definition without its uuids).
const upstreamFlowsJSON = \`${json}\`
`
fs.writeFileSync(OUT, code)
execFileSync("gofmt", ["-w", OUT])
console.log(`workflows: ${Object.keys(flows).length}`)
