#!/usr/bin/env node
//
// Generates the Go DML models from the compiled Medusa modules.
//
// Usage:
//   node scripts/extract-models.mjs [UPSTREAM_DIR]
//
// For every module, each DML entity exported by src/models is written to
// packages/modules/<module>/src/models/<file>.go with:
//   - the DML definition (properties, relationships, indexes, checks,
//     cascades), as returned by the upstream parse() methods;
//   - the resolved metadata (table, columns, foreign keys, pivot tables)
//     upstream derives from it, read from MikroORM after initializing all the
//     entities of the module.
// Medusa Enterprise Edition modules are skipped.

import { execFileSync } from "node:child_process"
import { createRequire } from "node:module"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const UPSTREAM = path.resolve(process.argv[2] ?? path.join(ROOT, "reference/medusa"))
const VERSION = fs.readFileSync(path.join(ROOT, "UPSTREAM_VERSION"), "utf8").trim()
const GO_MODULE = "github.com/hitkey-io/medusago"
const HEADER = `// Code generated by scripts/extract-models.mjs from Medusa ${VERSION}. DO NOT EDIT.`

const require = createRequire(path.join(UPSTREAM, "package.json"))
const { toMikroORMEntity } = require("@medusajs/framework/utils")
const { MikroORM } = require("@medusajs/framework/mikro-orm/core")
const { PostgreSqlDriver } = require("@medusajs/framework/mikro-orm/postgresql")

const enterprisePaths = fs
  .readFileSync(path.join(UPSTREAM, "ENTERPRISE-LICENSE.md"), "utf8")
  .split("\n")
  .map((l) => l.match(/^- `(.*)`$/)?.[1])
  .filter(Boolean)
  .map((p) => p.replace(/\/$/, ""))

const isEntity = (v) => v && typeof v === "object" && v.schema && typeof v.parse === "function"
const entityName = (ref) => {
  const e = typeof ref === "function" ? ref() : ref
  return isEntity(e) ? e.parse().name : e?.name ?? String(e)
}
const clean = (o) => JSON.parse(JSON.stringify(o)) // drops undefined values

function checkExpression(check, columns) {
  if (typeof check === "function") {
    return { expression: check(columns) }
  }
  if (typeof check.expression === "function") {
    return { name: check.name, expression: check.expression(columns) }
  }
  return { name: check.name, expression: check.expression }
}

function dmlDefinition(entity) {
  const parsed = entity.parse()
  const properties = []
  const columns = new Proxy({}, { get: (_, k) => String(k) })
  for (const [name, prop] of Object.entries(entity.schema)) {
    const p = prop.parse(name)
    if (p.type) {
      const { pivotEntity, ...options } = p.options ?? {}
      properties.push({
        name,
        relation: {
          type: p.type,
          entity: entityName(p.entity),
          mappedBy: p.mappedBy,
          nullable: p.nullable,
          searchable: p.searchable,
          options: {
            ...options,
            ...(pivotEntity ? { pivotEntity: entityName(pivotEntity) } : {}),
            // "mappedBy" given as undefined: the relationship has no other side
            ...("mappedBy" in options && options.mappedBy === undefined ? { mappedByUndefined: true } : {}),
          },
        },
      })
    } else {
      properties.push({
        name,
        field: {
          dataType: p.dataType,
          nullable: p.nullable,
          computed: p.computed,
          primaryKey: p.primaryKey,
          defaultValue: p.defaultValue,
          indexes: p.indexes?.length ? p.indexes : undefined,
        },
      })
    }
  }
  return {
    name: parsed.name,
    tableName: parsed.tableName,
    properties,
    indexes: parsed.indexes,
    checks: (parsed.checks ?? []).map((c) => checkExpression(c, columns)),
    cascades: parsed.cascades,
  }
}

function resolvedMeta(meta) {
  const nameOf = (v) => (typeof v === "function" ? v().name : v?.className ?? v)
  return {
    className: meta.className,
    collection: meta.collection,
    primaryKeys: meta.primaryKeys,
    properties: Object.values(meta.properties).map((p) => ({
      name: p.name,
      kind: p.kind,
      type: typeof p.type === "string" ? p.type : p.type?.name,
      columnType: p.columnTypes?.length === 1 ? p.columnTypes[0] : p.columnType,
      fieldNames: p.fieldNames,
      nullable: !!p.nullable,
      primary: p.primary,
      persist: p.persist === false ? false : undefined,
      autoincrement: p.autoincrement,
      default: p.default,
      defaultRaw: p.defaultRaw,
      items: Array.isArray(p.items) ? p.items : undefined,
      entity: p.kind === "scalar" ? undefined : p.type,
      mappedBy: p.mappedBy,
      inversedBy: p.inversedBy,
      owner: p.owner,
      mapToPk: p.mapToPk,
      deleteRule: p.deleteRule,
      pivotTable: p.pivotTable,
      pivotEntity: p.pivotEntity ? nameOf(p.pivotEntity) : undefined,
      joinColumns: p.kind === "m:n" ? p.joinColumns : undefined,
      inverseJoinColumns: p.kind === "m:n" ? p.inverseJoinColumns : undefined,
      referencedColumnNames: p.kind === "scalar" ? undefined : p.referencedColumnNames,
    })),
  }
}

const goIdent = (name) => name.replace(/[^A-Za-z0-9_]/g, "")
const report = []

for (const mod of fs.readdirSync(path.join(UPSTREAM, "packages/modules")).sort()) {
  const pkgDir = `packages/modules/${mod}`
  const distModels = path.join(UPSTREAM, pkgDir, "dist/models")
  if (!fs.existsSync(path.join(distModels, "index.js")) || enterprisePaths.includes(pkgDir)) {
    continue
  }

  const index = require(path.join(distModels, "index.js"))
  const entities = Object.values(index).filter(isEntity)
  if (!entities.length) {
    continue
  }

  const orm = await MikroORM.init({
    driver: PostgreSqlDriver,
    entities: entities.map((e) => toMikroORMEntity(e)),
    dbName: "unused",
    connect: false,
    discovery: { warnWhenNoEntities: false },
  })
  const metadata = orm.getMetadata()

  const outDir = path.join(ROOT, pkgDir, "src/models")
  fs.mkdirSync(outDir, { recursive: true })
  for (const f of fs.readdirSync(outDir)) {
    if (f.endsWith(".go") && fs.readFileSync(path.join(outDir, f), "utf8").startsWith(HEADER)) {
      fs.rmSync(path.join(outDir, f))
    }
  }

  const written = new Map()
  for (const file of fs.readdirSync(distModels).sort()) {
    if (!file.endsWith(".js") || file === "index.js") {
      continue
    }
    const exported = require(path.join(distModels, file))
    const vars = []
    for (const [exportName, value] of Object.entries(exported)) {
      if (!isEntity(value) || !entities.includes(value) || written.has(value)) {
        continue
      }
      const indexName = Object.entries(index).find(([, v]) => v === value)[0]
      const definition = dmlDefinition(value)
      const className = toMikroORMEntity(value).name
      const json = JSON.stringify(clean({ ...definition, meta: resolvedMeta(metadata.find(className)) }), null, 2)
      if (json.includes("`")) {
        throw new Error(`${mod}/${file}: backtick in model`)
      }
      vars.push(`// ${indexName} mirrors the ${definition.name} model of ${pkgDir}/src/models/${file.replace(/\.js$/, ".ts")}.\nvar ${goIdent(indexName)} = dml.MustParseEntity(\`${json}\`)`)
      written.set(value, goIdent(indexName))
      void exportName
    }
    if (vars.length) {
      fs.writeFileSync(
        path.join(outDir, file.replace(/\.js$/, ".go")),
        `${HEADER}\n\npackage models\n\nimport "${GO_MODULE}/packages/core/utils/src/dml"\n\n${vars.join("\n\n")}\n`
      )
    }
  }
  await orm.close(true)

  // The module joiner config: linkable keys, aliases (with the generated
  // method suffixes) and the GraphQL schema used by Query.
  const definition = require(path.join(UPSTREAM, pkgDir, "dist/index.js")).default
  const joinerConfig = definition?.service?.prototype?.__joinerConfig?.()
  if (joinerConfig) {
    const json = JSON.stringify(clean(joinerConfig), null, 2)
    if (json.includes("`")) {
      throw new Error(`${mod}: backtick in joiner config`)
    }
    fs.writeFileSync(
      path.join(ROOT, pkgDir, "src/joiner-config.go"),
      `${HEADER}\n\npackage ${mod.replace(/-/g, "")}\n\nimport "${GO_MODULE}/packages/core/types/src/joiner"\n\n// JoinerConfig mirrors the joiner configuration of the module service.\nvar JoinerConfig = joiner.MustParseModuleJoinerConfig(\`${json}\`)\n`
    )
  }

  const ordered = entities.filter((e) => written.has(e)).map((e) => written.get(e))
  fs.writeFileSync(
    path.join(outDir, "index.go"),
    `${HEADER}

// Package models holds the data models of the ${mod} module.
package models

import "${GO_MODULE}/packages/core/utils/src/dml"

// All lists the module models in upstream export order.
var All = []*dml.Entity{
${ordered.map((n) => `\t${n},`).join("\n")}
}
`
  )
  report.push(`${mod}: ${ordered.length}`)
  execFileSync("gofmt", ["-w", outDir])
}

console.log(`modules with models: ${report.length}, models: ${report.reduce((n, l) => n + Number(l.split(": ")[1]), 0)}`)
for (const line of report) console.log(`  ${line}`)
