#!/usr/bin/env node
//
// Generates packages/core/core-flows/src/common/steps/remote-query-steps.go
// from the upstream core-flows sources: the steps of every workflow that
// are a useRemoteQueryStep (keyed by workflow id and step name). The Go
// workflows read through useQueryGraphStep-like helpers; the output of a
// remote query step is the rows (or the first row with list: false), not
// { data, metadata }, and the journal of a run shows it that way.
//
// Usage:
//   node scripts/extract-remote-query-steps.mjs
//
// Workflows of the Medusa Enterprise Edition (RBAC) are skipped.

import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const VERSION = fs.readFileSync(path.join(ROOT, "UPSTREAM_VERSION"), "utf8").trim()
const SRC = path.join(ROOT, "reference/medusa/packages/core/core-flows/src")
const HEADER = `// Code generated by scripts/extract-remote-query-steps.mjs from Medusa ${VERSION}. DO NOT EDIT.`
const OUT = path.join(ROOT, "packages/core/core-flows/src/common/steps/remote-query-steps.go")

const ENTERPRISE = /rbac/

const files = []
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) {
      if (e.name !== "__tests__" && !ENTERPRISE.test(e.name)) {
        walk(p)
      }
    } else if (e.name.endsWith(".ts")) {
      files.push(p)
    }
  }
}
walk(SRC)

// string constants of every file (workflow ids are often imported)
const constants = {}
for (const f of files) {
  const s = fs.readFileSync(f, "utf8")
  for (const m of s.matchAll(/export const (\w+)\s*=\s*"([^"]+)"/g)) {
    constants[m[1]] = m[2]
  }
}

const closing = (s, from) => {
  let depth = 1
  let i = from
  while (depth > 0 && i < s.length) {
    const c = s[i]
    if (c === "(") depth++
    else if (c === ")") depth--
    i++
  }
  return i
}

const steps = {}
for (const f of files) {
  const s = fs.readFileSync(f, "utf8")
  const workflows = [...s.matchAll(/createWorkflow\(\s*(?:\{\s*name:\s*)?("([^"]+)"|(\w+))/g)].map((m) => ({
    at: m.index,
    id: m[2] ?? constants[m[3]],
  }))
  for (const m of s.matchAll(/useRemoteQueryStep\(/g)) {
    const end = closing(s, m.index + m[0].length)
    const config = s.slice(end, end + 200).match(/^\s*\.config\(\{\s*name:\s*"([^"]+)"/)
    const name = config ? config[1] : "use-remote-query"
    const wf = workflows.filter((w) => w.at < m.index).pop()
    if (!wf?.id) {
      continue
    }
    ;(steps[wf.id] ??= new Set()).add(name)
  }
}

const lines = Object.keys(steps)
  .sort()
  .map((id) => `\t${JSON.stringify(id)}: {${[...steps[id]].sort().map((n) => `${JSON.stringify(n)}: true`).join(", ")}},`)

const code = `${HEADER}

package steps

// remoteQuerySteps lists, by workflow id, the steps upstream runs as a
// useRemoteQueryStep.
var remoteQuerySteps = map[string]map[string]bool{
${lines.join("\n")}
}
`
fs.writeFileSync(OUT, code)
execFileSync("gofmt", ["-w", OUT])
console.log(`workflows: ${lines.length}`)
