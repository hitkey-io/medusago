#!/usr/bin/env node
//
// Generates Go migrations from the compiled Medusa module migrations.
//
// Usage:
//   node scripts/extract-migrations.mjs [UPSTREAM_DIR]
//
// UPSTREAM_DIR defaults to reference/medusa and must be built (dist/ present).
//
// Every upstream migration class is instantiated with a stub driver and its
// up()/down() are run; the SQL passed to addSql() is captured and written to
// packages/modules/[providers/]<name>/src/migrations/<MigrationName>.go (and
// packages/plugins/<plugin>/src/modules/<name>/migrations), keeping the
// upstream name so the rows in mikro_orm_migrations stay identical.
//
// Modules listed as Medusa Enterprise Edition materials in the upstream
// ENTERPRISE-LICENSE.md are skipped.
//
// Migrations that read from the database (this.execute, getKnex, ...) cannot
// be captured statically. They are reported and must be ported by hand; the
// generator never overwrites a hand-written file (one without the generated
// header).

import { execFileSync } from "node:child_process"
import { createRequire } from "node:module"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const UPSTREAM = path.resolve(process.argv[2] ?? path.join(ROOT, "reference/medusa"))
const VERSION = fs.readFileSync(path.join(ROOT, "UPSTREAM_VERSION"), "utf8").trim()
const GO_MODULE = "github.com/hitkey-io/medusago"
const HEADER = `// Code generated by scripts/extract-migrations.mjs from Medusa ${VERSION}. DO NOT EDIT.`

const require = createRequire(path.join(UPSTREAM, "package.json"))

class DynamicMigrationError extends Error {}

const stubDriver = new Proxy(
  {},
  {
    get() {
      return () => {
        throw new DynamicMigrationError("migration accesses the database")
      }
    },
  }
)

// Captures the statements of a migration that runs a single read query and
// then only calls addSql, for both outcomes of that query: no rows ("missing")
// and one row ("exists"). Returns null when the migration does anything else
// with the database (more reads, writes through execute, ...).
async function captureBranches(Cls) {
  const branches = {}
  for (const [branch, rows] of [
    ["Missing", []],
    ["Exists", [{}]],
  ]) {
    let calls = 0
    const driver = new Proxy(
      {},
      {
        get(_, prop) {
          if (prop === "execute") {
            return async () => {
              calls++
              if (calls > 1) {
                throw new DynamicMigrationError("more than one database call")
              }
              return rows
            }
          }
          return () => {
            throw new DynamicMigrationError("migration accesses the database")
          }
        },
      }
    )
    const instance = new Cls(driver, {})
    let result
    try {
      result = await capture(instance, "up")
    } catch (err) {
      if (err instanceof DynamicMigrationError) {
        return null
      }
      throw err
    }
    if (result.dynamic || calls !== 1) {
      return null
    }
    branches[branch] = result.queries
  }
  return branches
}

async function capture(instance, method) {
  instance.reset()
  try {
    await instance[method]()
  } catch (err) {
    if (err instanceof DynamicMigrationError) {
      return { dynamic: true }
    }
    if (method === "down" && /cannot be reverted/.test(err?.message ?? "")) {
      return { queries: null }
    }
    throw err
  }

  const queries = instance.getQueries().map((q) => {
    if (typeof q === "string") {
      return q
    }
    if (q && typeof q.toQuery === "function") {
      return q.toQuery()
    }
    throw new Error(`unsupported query type: ${typeof q}`)
  })
  return { queries }
}

// Values generated while a migration runs (ulid() in the upstream template
// strings) differ between two captures. They are replaced with ULID_MARKER,
// which the Go migrator substitutes with a fresh ULID at execution time.
const ULID_MARKER = "__MEDUSA_GENERATED_ULID__"
const ULID_RE = /[0-9A-HJKMNP-TV-Z]{26}/g

function markGenerated(first, second) {
  if (first === null || second === null) {
    return first
  }
  return first.map((q, i) => {
    if (q === second[i]) {
      return q
    }
    const a = q.match(ULID_RE) ?? []
    const b = second[i].match(ULID_RE) ?? []
    const replaceDiffering = (stmt, mine, theirs) =>
      mine.reduce(
        (acc, token, j) => (token !== theirs[j] ? acc.replace(token, ULID_MARKER) : acc),
        stmt
      )
    const marked = replaceDiffering(q, a, b)
    if (marked !== replaceDiffering(second[i], b, a)) {
      throw new Error(`non-deterministic statement that is not a ULID:\n${q}`)
    }
    return marked
  })
}

function goString(s) {
  if (!s.includes("`")) {
    return "`" + s + "`"
  }
  return JSON.stringify(s)
}

function goStringSlice(queries, indent) {
  if (queries === null) {
    return "nil"
  }
  if (queries.length === 0) {
    return "[]string{}"
  }
  const pad = "\t".repeat(indent)
  return (
    "[]string{\n" +
    queries.map((q) => `${pad}\t${goString(q)},`).join("\n") +
    `\n${pad}}`
  )
}

function isGenerated(file) {
  return fs.existsSync(file) && fs.readFileSync(file, "utf8").startsWith(HEADER)
}

const enterprisePaths = fs
  .readFileSync(path.join(UPSTREAM, "ENTERPRISE-LICENSE.md"), "utf8")
  .split("\n")
  .map((l) => l.match(/^- `(.*)`$/)?.[1])
  .filter(Boolean)
  .map((p) => p.replace(/\/$/, ""))

const report = { generated: 0, dynamic: [], modules: [] }

const packageDirs = ["packages/modules", "packages/modules/providers"].flatMap((base) =>
  fs
    .readdirSync(path.join(UPSTREAM, base))
    .filter((name) => name !== "providers")
    .map((name) => `${base}/${name}`)
)

// The modules of the plugins: packages/plugins/<plugin>/src/modules/<name>,
// compiled into .medusa/server/src/modules/<name>/migrations.
const pluginModules = fs
  .readdirSync(path.join(UPSTREAM, "packages/plugins"))
  .flatMap((plugin) => {
    const modulesDir = path.join(UPSTREAM, "packages/plugins", plugin, "src/modules")
    if (!fs.existsSync(modulesDir)) return []
    return fs
      .readdirSync(modulesDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => ({
        pkgDir: `packages/plugins/${plugin}/src/modules/${d.name}`,
        distDir: path.join(UPSTREAM, "packages/plugins", plugin, ".medusa/server/src/modules", d.name, "migrations"),
        srcDir: path.join(modulesDir, d.name, "migrations"),
        outDir: path.join(ROOT, "packages/plugins", plugin, "src/modules", d.name, "migrations"),
      }))
  })

const entries = packageDirs.sort().map((pkgDir) => ({
  pkgDir,
  distDir: path.join(UPSTREAM, pkgDir, "dist/migrations"),
  srcDir: path.join(UPSTREAM, pkgDir, "src/migrations"),
  outDir: path.join(ROOT, pkgDir, "src/migrations"),
})).concat(pluginModules)

for (const { pkgDir, distDir, srcDir, outDir } of entries) {
  const mod = path.basename(pkgDir)
  if (!fs.existsSync(srcDir) || enterprisePaths.includes(pkgDir)) {
    continue
  }
  if (!fs.existsSync(distDir)) {
    throw new Error(`${mod}: ${distDir} is missing, build upstream first`)
  }

  const names = fs
    .readdirSync(srcDir)
    .filter((f) => f.endsWith(".ts") && !f.endsWith(".d.ts"))
    .map((f) => f.replace(/\.ts$/, ""))
    .sort()

  fs.mkdirSync(outDir, { recursive: true })

  for (const name of names) {
    const exported = require(path.join(distDir, `${name}.js`))
    const Cls = Object.values(exported).find((v) => typeof v === "function")
    if (!Cls) {
      throw new Error(`${mod}/${name}: no migration class exported`)
    }

    const instance = new Cls(stubDriver, {})
    const up = await capture(instance, "up")
    const down = await capture(instance, "down")
    if (!up.dynamic) {
      const again = await capture(new Cls(stubDriver, {}), "up")
      up.queries = markGenerated(up.queries, again.queries)
    }
    if (!down.dynamic) {
      const again = await capture(new Cls(stubDriver, {}), "down")
      down.queries = markGenerated(down.queries, again.queries)
    }
    const outFile = path.join(outDir, `${name}.go`)

    if (up.dynamic && !down.dynamic) {
      const branches = await captureBranches(Cls)
      if (branches) {
        const goName = name.replace(/[^A-Za-z0-9_]/g, "_")
        const branchFile = path.join(outDir, `${name}.branches.go`)
        fs.writeFileSync(
          branchFile,
          `${HEADER}

package migrations

// Statements of ${name} when the table it checks is missing.
var ${goName}UpWhenMissing []string = ${goStringSlice(branches.Missing, 0)}

// Statements of ${name} when the table it checks exists.
var ${goName}UpWhenExists []string = ${goStringSlice(branches.Exists, 0)}

// Down statements of ${name} (nil: cannot be reverted).
var ${goName}Down []string = ${goStringSlice(down.queries, 0)}
`
        )
        report.branched = (report.branched ?? 0) + 1
      }
    }

    if (up.dynamic || down.dynamic) {
      report.dynamic.push(`${mod}/${name}${fs.existsSync(outFile) && !isGenerated(outFile) ? " (hand-written)" : " (MISSING)"}`)
      continue
    }
    if (fs.existsSync(outFile) && !isGenerated(outFile)) {
      continue
    }

    const goName = name.replace(/[^A-Za-z0-9_]/g, "_")
    const code = `${HEADER}

package migrations

import (
	m "${GO_MODULE}/packages/core/utils/src/migrations"
)

var ${goName} = m.Migration{
	Name: ${JSON.stringify(name)},
	Up: ${goStringSlice(up.queries, 1)},
	Down: ${goStringSlice(down.queries, 1)},
}
`
    fs.writeFileSync(outFile, code)
    report.generated++
  }

  // index.go lists the module migrations in upstream execution order.
  const index = `${HEADER}

// Package migrations holds the database migrations of the ${mod} module.
package migrations

import (
	m "${GO_MODULE}/packages/core/utils/src/migrations"
)

// Migrations lists the module migrations in execution order.
var Migrations = []m.Migration{
${names.map((n) => `\t${n.replace(/[^A-Za-z0-9_]/g, "_")},`).join("\n")}
}
`
  fs.writeFileSync(path.join(outDir, "index.go"), index)
  report.modules.push(`${pkgDir}: ${names.length}`)
}

execFileSync("gofmt", ["-w", ...entries.map((e) => e.outDir).filter((d) => fs.existsSync(d))])

console.log(`modules: ${report.modules.length}`)
for (const line of report.modules) console.log(`  ${line}`)
console.log(`generated migrations: ${report.generated}`)
console.log(`generated branch captures: ${report.branched ?? 0}`)
if (report.dynamic.length) {
  console.log(`hand-ported migrations (${report.dynamic.length}):`)
  for (const line of report.dynamic) console.log(`  ${line}`)
}
